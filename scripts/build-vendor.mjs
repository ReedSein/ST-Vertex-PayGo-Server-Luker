// Builds vendor/isomorphic-git.bundle.cjs from the pinned devDependencies.
//
// The bundle is committed because users must be able to install and update the
// plugin without npm. Run this only after changing the pinned versions, then
// commit the rebuilt file. `--check` rebuilds into memory and fails when the
// committed bundle no longer matches, so a stale artifact cannot pass review.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'scripts', 'vendor-entry.mjs');
const target = path.join(root, 'vendor', 'isomorphic-git.bundle.cjs');
const check = process.argv.includes('--check');

const result = await build({
    entryPoints: [entry],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    external: ['node:*'],
    legalComments: 'inline',
    banner: {
        js: '/* Generated by scripts/build-vendor.mjs. Do not edit. '
            + 'Source: isomorphic-git and isomorphic-git/http/node at the versions in package.json. */',
    },
    write: false,
});

const [produced] = result.outputFiles;
if (produced === undefined) {
    console.error('ERROR: esbuild produced no output.');
    process.exitCode = 1;
} else if (check) {
    let committed = '';
    try {
        committed = await readFile(target, 'utf8');
    } catch (error) {
        console.error(`ERROR: cannot read ${path.relative(root, target)}: ${error.message}`);
        process.exitCode = 1;
    }
    if (committed !== produced.text) {
        console.error('ERROR: vendor/isomorphic-git.bundle.cjs is stale. Run node scripts/build-vendor.mjs and commit the result.');
        process.exitCode = 1;
    } else {
        console.log(`Vendor bundle is current: ${produced.text.length} bytes.`);
    }
} else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, produced.text);
    console.log(`Wrote ${path.relative(root, target)}: ${produced.text.length} bytes.`);
}
